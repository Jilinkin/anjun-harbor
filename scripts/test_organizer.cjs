const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const html=fs.readFileSync(path.join(__dirname,'..','manager.html'),'utf8');
const code=html.split('// BEGIN ORGANIZER ENGINE')[1].split('// END ORGANIZER ENGINE')[0];
const ctx=vm.createContext({});
vm.runInContext(code,ctx);
const {organize,assessment,applyOrganization}=ctx;
const now=Date.parse('2026-01-10T00:00:00Z');
const site=(key,extra={})=>({key,name:key,api:'https://example.com/'+key,type:1,approved:true,probe:true,...extra});
const group=(...sites)=>({id:'featured',name:'Featured',sites});
const catalog=(...groups)=>({version:1,groups});
const row=(s,score,status='metadata_ok')=>({group:'featured',key:s.key,api:s.api,score,status});
const report=(...checks)=>({checked_at:new Date(now-1000).toISOString(),checks});
const a=site('a'),b=site('b'),c=site('c'),locked=site('lock',{locked:true}),disabled=site('disabled',{approved:false});
const keys=p=>Array.from(p.groups[0].rows,x=>x.key);
assert.deepEqual(keys(organize(catalog(group(a,locked,b,disabled,c)),report(row(a,20,'http_error'),row(b,90),row(c,60)),now)),['b','lock','c','disabled','a']);
assert.equal(assessment(group(a),a,{checked_at:'2025-01-01',checks:[row(a,100)]},now).tier,'unknown');
assert.equal(assessment(group(a),a,report({...row(a,100),api:'https://example.com/changed'}),now).tier,'unknown');
assert.equal(assessment(group(a),a,report(row(a,101)),now).tier,'unknown');
assert.equal(assessment(group(a),a,report(row(a,100),row(a,0)),now).tier,'unknown');
assert.equal(assessment(group(a),{...a,probe:false},report(row(a,100)),now).tier,'unknown');
assert.deepEqual(keys(organize(catalog(group(a,b)),report(),now)),['a','b']);
const dup=organize(catalog(group(a,site('duplicate',{api:a.api}))),report(),now);
assert.equal(dup.duplicates.length,1);
const original=catalog(group(a,b));const p=organize(original,report(row(a,50),row(b,100)),now);
const next=applyOrganization(original,p);
assert.deepEqual(Array.from(next.groups[0].sites,x=>x.key),['b','a']);
assert.deepEqual(original.groups[0].sites.map(x=>x.key),['a','b']);
assert.throws(()=>applyOrganization(catalog(group(b,a)),p),/过期/);
console.log('Organizer: 11 assertions passed');
